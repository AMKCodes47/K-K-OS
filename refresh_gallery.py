#!/usr/bin/env python3
"""Scan the K&K OS media folders and write media-manifest.js.

Supported photos: .jpg .jpeg .png .webp .gif
Supported videos: .mp4 .webm .mov
Optional video poster/cover: name-cover.jpg/png/webp beside name.mp4.
Profile photos: media/profiles/kartik.jpg and media/profiles/kritika.jpg (or PNG/WebP).
"""
from pillow_heif import register_heif_opener
from PIL import Image

register_heif_opener()
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parent
MEDIA_ROOT = ROOT / "media"
MEMORY_ROOT = MEDIA_ROOT / "memory-vault"
PROFILES_ROOT = MEDIA_ROOT / "profiles"
OUT = ROOT / "media-manifest.js"
IMAGE_EXT = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".heic", ".heif"}
VIDEO_EXT = {".mp4", ".webm", ".mov"}
OWNER_DIRS = ("kartik", "kritika", "shared")
from pathlib import Path

def prepare_image(path):
    path = Path(path)

    if path.suffix.lower() in {".heic", ".heif"}:
        output = path.with_suffix(".jpg")

        with Image.open(path) as image:
            image.convert("RGB").save(
                output, "JPEG", quality=92
            )

        return output

    return path

def title_from_filename(filename: str) -> str:
    """Use the filename (sans extension) as the Polaroid's title."""
    stem = Path(filename).stem
    # Turn separators into spaces, preserve intentional words and punctuation otherwise.
    stem = re.sub(r"[_]+", " ", stem)
    stem = re.sub(r"\s+", " ", stem).strip()
    return stem or "Untitled memory"

def relative_url(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()

def main() -> None:
    items = []
    for owner in OWNER_DIRS:
        folder = MEMORY_ROOT / owner
        folder.mkdir(parents=True, exist_ok=True)
        files = sorted((p for p in folder.iterdir() if p.is_file()), key=lambda p: p.name.casefold())
        # A matching name-cover image is used for the video poster and not shown separately as a Polaroid.
        cover_candidates = {p.stem[:-6].casefold(): p for p in files if p.suffix.lower() in IMAGE_EXT and p.stem.casefold().endswith("-cover")}
        for path in files:
            ext = path.suffix.lower()
            if ext not in IMAGE_EXT | VIDEO_EXT:
                continue
            if ext in IMAGE_EXT and path.stem.casefold().endswith("-cover"):
                continue
            kind = "video" if ext in VIDEO_EXT else "image"

            # Convert HEIC/HEIF photos into browser-compatible JPEGs.
            display_path = prepare_image(path) if kind == "image" else path

            cover = ""
            if kind == "video":
                candidate = cover_candidates.get(path.stem.casefold())
                if candidate:
                    cover = relative_url(candidate)
            items.append({
                "key": f"{owner}/{path.name}",
                "owner": owner,
                "filename": path.name,
                "title": title_from_filename(path.name),
                "type": kind,
                "src": relative_url(display_path),
                "cover": cover,
            })
    profiles = {}
    PROFILES_ROOT.mkdir(parents=True, exist_ok=True)
    for owner in ("kartik", "kritika"):
        candidates = [p for p in PROFILES_ROOT.iterdir() if p.is_file() and p.stem.casefold() == owner and p.suffix.lower() in IMAGE_EXT]
        if candidates:
            candidate = sorted(candidates, key=lambda p: (p.suffix.lower() != ".jpg", p.name.casefold()))[0]
            profiles[owner] = relative_url(candidate)
    payload = {"items": items, "profiles": profiles}
    OUT.write_text("/* Auto-generated by refresh_gallery.py. Do not hand-edit this file. */\nwindow.KK_MEDIA = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
    print(f"K&K OS media catalogue refreshed: {len(items)} item(s) found.")
    print(f"Profile pictures found: {', '.join(profiles.keys()) if profiles else 'none yet'}")
    print("Titles come from filenames; dates and captions live in data.js or Edit Mode.")

if __name__ == "__main__":
    main()
